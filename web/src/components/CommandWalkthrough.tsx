import React, { useEffect, useRef, useState } from 'react';
import {
  AlertTriangle,
  BarChart2,
  Check,
  FileText,
  Folder,
  FolderOpen,
  Minus,
  Plus,
  RotateCw,
  Scan,
  ShieldCheck,
} from 'lucide-react';
import { AnimatePresence, motion, useReducedMotion } from 'motion/react';
import { WORKSPACE_ARTIFACTS, formatSize } from '../data';
import { WorkspaceArtifact } from '../types';
import CleanupGuide from './CleanupGuide';

type TabId = 'scan' | 'analyze' | 'explain';

const TABS: {
  id: TabId;
  label: string;
  description: string;
  command: string;
}[] = [
  {
    id: 'scan',
    label: 'Scan',
    description: 'Find leftover artifacts.',
    command: 'devklean scan ~/projects',
  },
  {
    id: 'analyze',
    label: 'Analyze',
    description: 'Review each artifact.',
    command: 'devklean analyze ~/projects',
  },
  {
    id: 'explain',
    label: 'Explain',
    description: 'Understand a folder.',
    command: 'devklean explain',
  },
];

function whatItIsLabel(item: WorkspaceArtifact): string {
  switch (item.id) {
    case 'node_modules':
      return 'Node.js dependency directory installed by npm, yarn, or pnpm.';
    case 'venv':
      return 'Python virtual environment directory holding isolated packages.';
    case 'next':
      return 'Next.js compiled build output and development cache directory.';
    case 'dist':
      return 'Compiled distribution output directory generated by project build tooling.';
    default:
      return `${item.ecosystem} directory.`;
  }
}

function whatToConsider(item: WorkspaceArtifact): string {
  const confidencePct = Math.round(item.confidence * 100);
  const riskLabel = item.risk === 'low' ? 'Low risk' : 'Medium risk';
  const conflictNote = item.lockfileConflict
    ? ' Conflicting package-manager lockfiles were flagged in this project, so confirm which tool you intend to run before regenerating.'
    : '';
  return `${riskLabel} (${confidencePct}% fixed signature confidence, not a safety probability). ${item.rationale}${conflictNote}`;
}

export default function CommandWalkthrough() {
  const shouldReduceMotion = useReducedMotion();
  const [activeTab, setActiveTab] = useState<TabId>('scan');
  const [selectedId, setSelectedId] = useState<string>(WORKSPACE_ARTIFACTS[0].id);

  // Scan replay state
  const [replayCount, setReplayCount] = useState(0);
  const [isReplaying, setIsReplaying] = useState(false);
  const [scanComplete, setScanComplete] = useState(true);
  const [liveAnnouncement, setLiveAnnouncement] = useState('');

  // Analyze inline terminology disclosure
  const [glossaryOpen, setGlossaryOpen] = useState(false);

  const tabRefs = useRef<Record<TabId, HTMLButtonElement | null>>({
    scan: null,
    analyze: null,
    explain: null,
  });
  const timersRef = useRef<number[]>([]);

  const clearTimers = () => {
    timersRef.current.forEach((id) => window.clearTimeout(id));
    timersRef.current = [];
  };

  useEffect(() => {
    return () => clearTimers();
  }, []);

  const selectedArtifact =
    WORKSPACE_ARTIFACTS.find((item) => item.id === selectedId) ?? WORKSPACE_ARTIFACTS[0];
  const totalMB = WORKSPACE_ARTIFACTS.reduce((sum, item) => sum + item.sizeMB, 0);

  const activeCommand =
    activeTab === 'explain'
      ? `devklean explain ${selectedArtifact.path}`
      : TABS.find((tab) => tab.id === activeTab)!.command;

  const triggerReplay = () => {
    clearTimers();
    setReplayCount((prev) => prev + 1);

    if (shouldReduceMotion) {
      setIsReplaying(false);
      setScanComplete(true);
      setLiveAnnouncement(
        `Sample scan complete: ${WORKSPACE_ARTIFACTS.length} directories, ${formatSize(totalMB)} total. Nothing changed.`,
      );
      return;
    }

    setIsReplaying(true);
    setScanComplete(false);
    setLiveAnnouncement('');

    const doneTimer = window.setTimeout(() => {
      setIsReplaying(false);
      setScanComplete(true);
      setLiveAnnouncement(
        `Sample scan complete: ${WORKSPACE_ARTIFACTS.length} directories, ${formatSize(totalMB)} total. Nothing changed.`,
      );
    }, 620);

    timersRef.current.push(doneTimer);
  };

  const handleTabKeyDown = (e: React.KeyboardEvent, index: number) => {
    let nextIndex: number | null = null;
    if (e.key === 'ArrowRight') nextIndex = (index + 1) % TABS.length;
    if (e.key === 'ArrowLeft') nextIndex = (index - 1 + TABS.length) % TABS.length;
    if (e.key === 'Home') nextIndex = 0;
    if (e.key === 'End') nextIndex = TABS.length - 1;

    if (nextIndex !== null) {
      e.preventDefault();
      const nextTab = TABS[nextIndex];
      setActiveTab(nextTab.id);
      tabRefs.current[nextTab.id]?.focus();
    }
  };

  const renderTabIcon = (id: TabId) => {
    if (id === 'scan') {
      return (
        <span className="relative inline-flex h-4 w-4 items-center justify-center">
          <Scan className="h-4 w-4" strokeWidth={1.6} aria-hidden="true" />
          {isReplaying && !shouldReduceMotion && (
            <motion.span
              key={`sweep-${replayCount}`}
              initial={{ top: '1px', opacity: 0.9 }}
              animate={{ top: '13px', opacity: 0 }}
              transition={{ duration: 0.42, ease: 'easeInOut' }}
              className="pointer-events-none absolute right-[2px] left-[2px] h-[1.5px] bg-[#F5F5F5]"
              aria-hidden="true"
            />
          )}
        </span>
      );
    }
    if (id === 'analyze') {
      return <BarChart2 className="h-4 w-4" strokeWidth={1.6} aria-hidden="true" />;
    }
    return <FileText className="h-4 w-4" strokeWidth={1.6} aria-hidden="true" />;
  };

  return (
    <section id="walkthrough" className="w-full scroll-mt-16 border-b border-[#333333] bg-[#111111] py-14 md:py-20">
      <div className="mx-auto max-w-[1200px] px-5 md:px-6 lg:px-8">
        <div className="mb-10 max-w-2xl">
          <h2 className="font-sans text-[32px] font-medium leading-[1.1] tracking-[-0.025em] text-[#F5F5F5] md:text-[42px]">
            See what’s there. Decide what goes.
          </h2>
          <p className="mt-3 font-sans text-[16px] leading-[1.6] text-[#ADADAD]">
            Start with three read-only commands, then preview and confirm a cleanup. Explore this sample workspace; nothing here touches your files.
          </p>
        </div>

        {/* Single wide walkthrough container */}
        <div className="overflow-hidden rounded-[8px] border border-[#333333] bg-[#191919]">
          {/* Tabs bar + readable Sample workspace label */}
          <div className="flex flex-col justify-between border-b border-[#333333] lg:flex-row lg:items-stretch">
            <div
              role="tablist"
              aria-label="DevKlean read-only commands"
              className="grid grid-cols-3 divide-x divide-[#333333] lg:flex-1"
            >
              {TABS.map((tab, index) => {
                const isActive = tab.id === activeTab;
                return (
                  <button
                    key={tab.id}
                    ref={(el) => {
                      tabRefs.current[tab.id] = el;
                    }}
                    type="button"
                    role="tab"
                    id={`tab-${tab.id}`}
                    aria-selected={isActive}
                    aria-controls={`panel-${tab.id}`}
                    tabIndex={isActive ? 0 : -1}
                    onClick={() => setActiveTab(tab.id)}
                    onKeyDown={(e) => handleTabKeyDown(e, index)}
                    className={`relative flex min-h-[48px] min-w-0 items-center justify-center px-2 py-3 text-left sm:justify-start sm:px-5 ${
                      isActive
                        ? 'bg-[#242424] text-[#F5F5F5]'
                        : 'text-[#ADADAD] hover:bg-[#242424]/60 hover:text-[#F5F5F5]'
                    }`}
                  >
                    <span className="inline-flex items-center gap-2 font-sans text-[14px] font-medium">
                      {renderTabIcon(tab.id)}
                      <span>{tab.label}</span>
                    </span>

                    {isActive && (
                      <motion.span
                        layoutId="walkthrough-tab-underline"
                        transition={{
                          duration: shouldReduceMotion ? 0 : 0.18,
                          ease: 'easeOut',
                        }}
                        className="absolute right-0 bottom-0 left-0 h-[2px] bg-[#F5F5F5]"
                        aria-hidden="true"
                      />
                    )}
                  </button>
                );
              })}
            </div>

            <div className="flex items-center justify-between border-t border-[#333333] px-4 py-2.5 sm:px-5 lg:border-t-0 lg:border-l">
              <span className="font-sans text-[13px] text-[#ADADAD]">{TABS.find((tab) => tab.id === activeTab)!.description} · Sample data</span>
            </div>
          </div>

          {/* Active command header */}
          <div className="flex flex-col justify-between gap-2 border-b border-[#333333] bg-[#111111] px-4 py-3 sm:flex-row sm:items-center sm:px-6">
            <code className="block min-w-0 [overflow-wrap:anywhere] font-mono text-[13px] text-[#F5F5F5] sm:text-[14px]">
              <span className="mr-2 select-none text-[#ADADAD]">$</span>
              {activeCommand}
            </code>

            {activeTab === 'scan' && (
              <button
                type="button"
                onClick={triggerReplay}
                aria-busy={isReplaying}
                className="inline-flex min-h-[44px] w-full shrink-0 items-center justify-center gap-2 rounded-[6px] border border-[#333333] bg-[#191919] px-3.5 py-2 font-sans text-[13px] font-medium text-[#F5F5F5] transition-colors hover:bg-[#242424] sm:w-auto"
              >
                <motion.span
                  key={`spin-${replayCount}`}
                  initial={{ rotate: 0 }}
                  animate={{ rotate: replayCount > 0 && !shouldReduceMotion ? 360 : 0 }}
                  transition={{ duration: 0.45, ease: 'easeOut' }}
                  className="inline-flex"
                  aria-hidden="true"
                >
                  <RotateCw className="h-3.5 w-3.5" strokeWidth={1.7} />
                </motion.span>
                <span>{isReplaying ? 'Replaying scan…' : 'Replay sample scan'}</span>
              </button>
            )}
          </div>

          {/* Screen-reader live region (final status announced once) */}
          <div className="sr-only" aria-live="polite" aria-atomic="true">
            {liveAnnouncement}
          </div>

          {/* Panel content */}
          <AnimatePresence mode="wait" initial={false}>
            <motion.div
              key={activeTab}
              id={`panel-${activeTab}`}
              role="tabpanel"
              tabIndex={0}
              aria-labelledby={`tab-${activeTab}`}
              initial={shouldReduceMotion ? false : { opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={shouldReduceMotion ? undefined : { opacity: 0 }}
              transition={{ duration: shouldReduceMotion ? 0 : 0.14 }}
            >
              {activeTab === 'scan' && (
                <div>
                  <div className="hidden grid-cols-12 border-b border-[#333333] px-6 py-2.5 font-sans text-[13px] text-[#ADADAD] sm:grid">
                    <div className="col-span-4">Directory</div>
                    <div className="col-span-6">Path</div>
                    <div className="col-span-2 text-right">Size</div>
                  </div>

                  <div className="divide-y divide-[#333333]">
                    {WORKSPACE_ARTIFACTS.map((item, idx) => (
                      <motion.div
                        key={`${item.id}-${replayCount}`}
                        initial={replayCount > 0 && !shouldReduceMotion ? { opacity: 0, y: 3 } : false}
                        animate={{ opacity: 1, y: 0 }}
                        transition={
                          replayCount > 0 && !shouldReduceMotion
                            ? { duration: 0.18, delay: idx * 0.06, ease: 'easeOut' }
                            : { duration: 0 }
                        }
                        className="flex flex-col gap-1 px-4 py-3.5 sm:grid sm:grid-cols-12 sm:items-center sm:gap-4 sm:px-6"
                      >
                        <div className="flex items-baseline justify-between sm:col-span-4 sm:block">
                          <span className="font-mono text-[13px] font-medium text-[#F5F5F5] sm:text-[14px]">
                            {item.dirName}
                          </span>
                          <span className="font-mono text-[13px] tabular-nums text-[#F5F5F5] sm:hidden">
                            {formatSize(item.sizeMB)}
                          </span>
                        </div>
                        <div className="min-w-0 [overflow-wrap:anywhere] font-mono text-[13px] text-[#CECECE] sm:col-span-6">
                          {item.path}
                        </div>
                        <div className="hidden text-right font-mono text-[13px] tabular-nums text-[#F5F5F5] sm:col-span-2 sm:block sm:text-[14px]">
                          {formatSize(item.sizeMB)}
                        </div>
                      </motion.div>
                    ))}
                  </div>

                  {/* Summary footer */}
                  <div className="flex flex-col justify-between gap-2 border-t border-[#333333] bg-[#111111] px-4 py-3.5 sm:flex-row sm:items-center sm:px-6">
                    <div className="inline-flex items-center gap-2 font-sans text-[14px] text-[#F5F5F5]">
                      {scanComplete ? (
                        <>
                          <Check className="h-4 w-4 shrink-0 text-[#F5F5F5]" strokeWidth={1.8} aria-hidden="true" />
                          <span>Scan complete. Nothing changed.</span>
                        </>
                      ) : (
                        <span className="text-[#ADADAD]">Scanning sample directories…</span>
                      )}
                    </div>

                    <div className="font-mono text-[13px] tabular-nums text-[#CECECE] sm:text-[14px]">
                      {scanComplete
                        ? `${WORKSPACE_ARTIFACTS.length} directories · ${formatSize(totalMB)}`
                        : 'Counting…'}
                    </div>
                  </div>
                </div>
              )}

              {activeTab === 'analyze' && (
                <div>
                  <div className="hidden grid-cols-12 border-b border-[#333333] px-6 py-2.5 font-sans text-[13px] text-[#ADADAD] sm:grid">
                    <div className="col-span-5">Directory &amp; Path</div>
                    <div className="col-span-5">Cleanup assessment</div>
                    <div className="col-span-2 text-right">Size</div>
                  </div>

                  {/* Anchored rows; only newly introduced assessment details fade in */}
                  <div className="divide-y divide-[#333333]">
                    {WORKSPACE_ARTIFACTS.map((item, idx) => (
                      <div
                        key={item.id}
                        className="grid grid-cols-1 gap-2.5 px-4 py-4 sm:grid-cols-12 sm:items-center sm:gap-4 sm:px-6"
                      >
                        {/* Anchored directory + path */}
                        <div className="sm:col-span-5">
                          <div className="flex items-baseline justify-between gap-2">
                            <span className="font-mono text-[13px] font-medium text-[#F5F5F5] sm:text-[14px]">
                              {item.dirName}
                            </span>
                            <span className="font-mono text-[13px] tabular-nums text-[#F5F5F5] sm:hidden">
                              {formatSize(item.sizeMB)}
                            </span>
                          </div>
                          <div className="mt-0.5 [overflow-wrap:anywhere] font-mono text-[13px] text-[#CECECE]">
                            {item.path}
                          </div>
                        </div>

                        {/* Animated assessment details */}
                        <motion.div
                          initial={shouldReduceMotion ? false : { opacity: 0, y: 2 }}
                          animate={{ opacity: 1, y: 0 }}
                          transition={{
                            duration: shouldReduceMotion ? 0 : 0.16,
                            delay: shouldReduceMotion ? 0 : idx * 0.04,
                          }}
                          className="flex flex-wrap items-center gap-x-3 gap-y-1.5 sm:col-span-5"
                        >
                          <span className="inline-flex items-center gap-1.5 rounded-[4px] border border-[#333333] bg-[#111111] px-2.5 py-1 font-sans text-[13px] text-[#F5F5F5]">
                            {item.risk === 'low' ? (
                              <ShieldCheck className="h-3.5 w-3.5 shrink-0 text-[#F5F5F5]" strokeWidth={1.6} aria-hidden="true" />
                            ) : (
                              <AlertTriangle className="h-3.5 w-3.5 shrink-0 text-[#F5F5F5]" strokeWidth={1.6} aria-hidden="true" />
                            )}
                            <span>{item.risk === 'low' ? 'Low risk' : 'Medium risk'}</span>
                          </span>

                          <span className="font-mono text-[13px] tabular-nums text-[#CECECE]">
                            {Math.round(item.confidence * 100)}% signature confidence
                          </span>

                          <span className="font-sans text-[13px] text-[#ADADAD]">
                            {item.staleDays}d since activity
                          </span>
                          {item.lockfileConflict && (
                            <div className="w-full border-l-2 border-[#F5F5F5] bg-[#242424] p-3 text-[13px] leading-relaxed text-[#F5F5F5]">
                              <span className="flex items-center gap-2 font-medium"><AlertTriangle className="h-4 w-4 shrink-0" aria-hidden="true" />Lockfile conflict — review first</span>
                              <p className="mt-1">Confirm which package manager and lockfile you’ll use to reinstall dependencies.</p>
                            </div>
                          )}
                        </motion.div>

                        <div className="hidden text-right font-mono text-[13px] tabular-nums text-[#F5F5F5] sm:col-span-2 sm:block sm:text-[14px]">
                          {formatSize(item.sizeMB)}
                        </div>
                      </div>
                    ))}
                  </div>

                  {/* Accessible inline help disclosure */}
                  <div className="border-t border-[#333333] bg-[#111111] px-4 py-3 sm:px-6">
                    <div className="flex flex-col justify-between gap-2 sm:flex-row sm:items-center">
                      <span className="font-sans text-[14px] text-[#CECECE]">
                        Signature confidence is a fixed registry score for the directory name, not a probability that removal is safe.
                      </span>

                      <button
                        type="button"
                        onClick={() => setGlossaryOpen((prev) => !prev)}
                        aria-expanded={glossaryOpen}
                        aria-controls="analyze-glossary"
                        className="inline-flex min-h-[44px] items-center gap-1.5 self-start font-sans text-[13px] font-medium text-[#F5F5F5] underline decoration-[#333333] underline-offset-4 transition-colors hover:decoration-[#F5F5F5] sm:self-auto"
                      >
                        {glossaryOpen ? (
                          <Minus className="h-3.5 w-3.5" strokeWidth={1.7} aria-hidden="true" />
                        ) : (
                          <Plus className="h-3.5 w-3.5" strokeWidth={1.7} aria-hidden="true" />
                        )}
                        <span>How are these assessed?</span>
                      </button>
                    </div>

                    {glossaryOpen && (
                      <div
                        id="analyze-glossary"
                        className="mt-2 grid gap-4 border-t border-[#333333] pt-3 sm:grid-cols-2"
                      >
                        <p className="font-sans text-[14px] leading-[1.6] text-[#ADADAD]">
                          <strong className="font-medium text-[#F5F5F5]">Risk tier:</strong> Maintainer-assigned
                          cleanup tier based on how reliably the folder can be rebuilt. Unrecognized names get no
                          verdict.
                        </p>
                        <p className="font-sans text-[14px] leading-[1.6] text-[#ADADAD]">
                          <strong className="font-medium text-[#F5F5F5]">Signature confidence:</strong> A maintainer-assigned score for how specific the
                          folder name is to one tool (for example, <code className="font-mono text-[13px] text-[#F5F5F5]">node_modules</code> is
                          more specific than <code className="font-mono text-[13px] text-[#F5F5F5]">dist</code>).
                        </p>
                      </div>
                    )}
                  </div>
                </div>
              )}

              {activeTab === 'explain' && (
                <div>
                  {/* Explicit selector instruction + folder choices */}
                  <div className="border-b border-[#333333] px-4 py-4 sm:px-6">
                    <div className="flex flex-col gap-3 lg:flex-row lg:items-center lg:justify-between">
                      <div>
                        <p id="explain-selector-label" className="font-sans text-[14px] font-medium text-[#F5F5F5]">
                          Choose a directory
                        </p>
                        <p className="mt-0.5 font-sans text-[14px] text-[#ADADAD]">
                          Choose a folder to see what created it and how to regenerate it.
                        </p>
                      </div>

                      <div
                        role="group"
                        aria-labelledby="explain-selector-label"
                        className="flex flex-wrap gap-2"
                      >
                        {WORKSPACE_ARTIFACTS.map((item) => {
                          const isSelected = item.id === selectedArtifact.id;
                          return (
                            <button
                              key={item.id}
                              type="button"
                              aria-pressed={isSelected}
                              onClick={() => setSelectedId(item.id)}
                              className={`inline-flex min-h-[44px] min-w-0 items-center gap-1.5 rounded-[6px] border px-2 py-2 sm:gap-2 sm:px-3.5 font-mono text-[13px] transition-colors ${
                                isSelected
                                  ? 'border-[#F5F5F5] bg-[#242424] text-[#F5F5F5]'
                                  : 'border-[#333333] bg-[#111111] text-[#CECECE] hover:bg-[#242424] hover:text-[#F5F5F5]'
                              }`}
                            >
                              {isSelected ? (
                                <motion.span
                                  key={`open-${item.id}`}
                                  initial={shouldReduceMotion ? false : { scale: 0.92, rotate: -6 }}
                                  animate={{ scale: 1, rotate: 0 }}
                                  transition={{ duration: shouldReduceMotion ? 0 : 0.16, ease: 'easeOut' }}
                                  className="inline-flex shrink-0"
                                  aria-hidden="true"
                                >
                                  <FolderOpen className="h-4 w-4 text-[#F5F5F5]" strokeWidth={1.6} />
                                </motion.span>
                              ) : (
                                <Folder className="h-4 w-4 shrink-0 text-[#ADADAD]" strokeWidth={1.6} aria-hidden="true" />
                              )}
                              <span>{item.dirName}</span>
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  </div>

                  {/* Readable 4-field explanation with short <=4px transition */}
                  <AnimatePresence mode="wait" initial={false}>
                    <motion.dl
                      key={selectedArtifact.id}
                      initial={shouldReduceMotion ? false : { opacity: 0, y: 4 }}
                      animate={{ opacity: 1, y: 0 }}
                      exit={shouldReduceMotion ? undefined : { opacity: 0, y: -2 }}
                      transition={{ duration: shouldReduceMotion ? 0 : 0.14, ease: 'easeOut' }}
                      className="divide-y divide-[#333333]"
                    >
                      <ExplainField label="What it is" value={whatItIsLabel(selectedArtifact)} />
                      <ExplainField label="What creates it" value={selectedArtifact.generatedBy} />
                      <ExplainField label="How to regenerate it" value={selectedArtifact.regenerateCommand} mono />
                      <ExplainField label="What to consider before cleanup" value={whatToConsider(selectedArtifact)} />
                    </motion.dl>
                  </AnimatePresence>

                  <div className="flex flex-col justify-between gap-2 border-t border-[#333333] bg-[#111111] px-4 py-3.5 font-sans text-[14px] text-[#ADADAD] sm:flex-row sm:items-center sm:px-6">
                    <span className="min-w-0 [overflow-wrap:anywhere]">
                      Inspecting <code className="font-mono text-[13px] text-[#F5F5F5]">{selectedArtifact.path}</code>
                    </span>
                    <span className="font-mono text-[13px] tabular-nums text-[#F5F5F5]">
                      {formatSize(selectedArtifact.sizeMB)}
                    </span>
                  </div>
                </div>
              )}
            </motion.div>
          </AnimatePresence>
        </div>
        <CleanupGuide />
      </div>
    </section>
  );
}

function ExplainField({ label, value, mono = false }: { label: string; value: string; mono?: boolean }) {
  return (
    <div className="grid grid-cols-1 gap-1.5 px-4 py-4 sm:grid-cols-12 sm:gap-6 sm:px-6">
      <dt className="font-sans text-[14px] font-medium text-[#ADADAD] sm:col-span-4">{label}</dt>
      <dd
        className={`break-words text-[#F5F5F5] sm:col-span-8 ${
          mono ? 'font-mono text-[13px] leading-[1.6] sm:text-[14px]' : 'font-sans text-[15px] leading-[1.6]'
        }`}
      >
        {value}
      </dd>
    </div>
  );
}
